package util

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// TestingWorkspaceDir returns ~/.novaworkbench/testing/<projectID>/<envID>/
// and creates it (mode 0o755) on first call, so callers don't have to
// MkdirAll before spawning npm or claude inside it.
//
// This is the Playwright workspace: package.json, node_modules,
// playwright.config.ts, tests/, specs/, .claude/agents/ and runs/<runID>/
// all live here. Keeping it under ~/.novaworkbench rather than inside the
// user's repo honours the same constraint as DiagramsDir — **永远不要写到需求
// 所在的项目根目录**. A test run creates tens of MB of node_modules,
// screenshots and trace.zip; none of that belongs in a git working tree.
//
// Per-environment override: a test_environments row may set
// workspace_override to point the workspace somewhere inside the repo (for
// teams that want the generated specs committed). THIS FUNCTION ONLY RETURNS
// THE DEFAULT — callers must check the row first:
//
//	dir := env.WorkspaceOverride
//	if dir == "" {
//	    dir, _ = util.TestingWorkspaceDir(env.ProjectID, env.ID)
//	}
//
// projectID and envID are NovaWorkbench-generated ids ("proj_…" / "tenv_…")
// and are joined as path segments. They are still sanitized here: a value
// containing a separator or ".." would otherwise let a caller escape the
// testing root, and this helper is the single place every caller funnels
// through.
func TestingWorkspaceDir(projectID, envID string) (string, error) {
	if err := validateIDSegment("projectID", projectID); err != nil {
		return "", err
	}
	if err := validateIDSegment("envID", envID); err != nil {
		return "", err
	}

	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("resolve home for testing dir: %w", err)
	}
	dir := filepath.Join(home, ".novaworkbench", "testing", projectID, envID)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", fmt.Errorf("mkdir testing workspace %s: %w", dir, err)
	}
	return dir, nil
}

// TestingRootDir returns ~/.novaworkbench/testing/ WITHOUT creating a
// per-environment subdirectory. Used by the retention trimmer to enumerate
// stale workspaces, and by settings to report total footprint.
func TestingRootDir() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("resolve home for testing root: %w", err)
	}
	dir := filepath.Join(home, ".novaworkbench", "testing")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", fmt.Errorf("mkdir testing root %s: %w", dir, err)
	}
	return dir, nil
}

// validateIDSegment rejects ids that are empty or contain path separators,
// ".." or NUL — i.e. anything that could escape the intended parent. Nova
// ids are generated by util.NewID and never trip this, but the check is
// cheap and this function is the choke point for path construction.
func validateIDSegment(name, val string) error {
	if val == "" {
		return fmt.Errorf("%s must not be empty", name)
	}
	if val == "." || val == ".." || strings.ContainsAny(val, `/\`) || strings.ContainsRune(val, 0) {
		return fmt.Errorf("%s %q contains an illegal path character", name, val)
	}
	return nil
}
