package model

import "time"

// ProjectClaudeDoc is the project-level CLAUDE.md asset: one row per
// project, shared by every requirement of that project.
//
// The content lives in the DB on purpose. A CLAUDE.md is a *managed asset*
// of the platform, not a file in the user's repository — it must work for
// projects that are not git repositories, and generating it must never
// dirty a working tree.
type ProjectClaudeDoc struct {
	ID        string `json:"id"`
	ProjectID string `json:"project_id"`
	// Content is the CLAUDE.md body (Markdown).
	Content string `json:"content"`
	// Source records how the current content came to be: generated by the
	// AI, hand-edited by the user, or imported from a CLAUDE.md that
	// already exists on disk.
	Source string `json:"source"`
	// GeneratedAt is the last time the AI regenerated the document. A
	// manual edit does NOT touch it — the badge answers "when was this
	// last machine-written", not "when did a human last save".
	GeneratedAt *time.Time `json:"generated_at,omitempty"`
	UpdatedAt   time.Time  `json:"updated_at"`
	// Bytes is the size of Content in bytes (not runes) — a cheap hint for
	// the UI and for the injection-side budget check.
	Bytes int `json:"bytes"`
}

// Sources for ProjectClaudeDoc.Source.
const (
	ProjectClaudeDocSourceGenerated = "generated"
	ProjectClaudeDocSourceManual    = "manual"
	ProjectClaudeDocSourceImported  = "imported"
)
